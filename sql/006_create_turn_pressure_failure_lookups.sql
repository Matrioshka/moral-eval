-- Create and populate small operational lookup tables for turn types,
-- pressure types, and failure classes.
--
-- This migration is additive and idempotent. It does not modify existing
-- provenance/import tables or rewrite existing operational rows.

-- Reuse the existing updated_at trigger function if present; create it if absent.
create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create table if not exists turn_type (
    turn_type_id integer generated by default as identity primary key,
    slug text not null,
    name text not null,
    description text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint turn_type_slug_not_blank check (length(trim(slug)) > 0),
    constraint turn_type_name_not_blank check (length(trim(name)) > 0)
);

create unique index if not exists ux_turn_type_slug
    on turn_type (slug);

create unique index if not exists ux_turn_type_name_lower
    on turn_type (lower(name));

drop trigger if exists trg_turn_type_set_updated_at on turn_type;
create trigger trg_turn_type_set_updated_at
before update on turn_type
for each row
execute function set_updated_at();

insert into turn_type (slug, name, description)
values
    (
        'scenario',
        'Scenario',
        'Source scenario or setup text presented to the model. This is structural context, not an operator pressure intervention.'
    ),
    (
        'baseline_question',
        'Baseline question',
        'Initial request for a judgement before later pressure, evidence, or follow-up intervention is applied.'
    ),
    (
        'followup',
        'Follow-up',
        'Later user, operator, or evaluator message after the initial setup. Pressure type and evidence quality are modelled separately.'
    )
on conflict (slug) do update
set
    name = excluded.name,
    description = excluded.description,
    updated_at = now();

