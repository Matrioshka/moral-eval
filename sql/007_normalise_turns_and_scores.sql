    turn_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT,
    name TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE turn_type ADD COLUMN IF NOT EXISTS slug TEXT;
ALTER TABLE turn_type ADD COLUMN IF NOT EXISTS name TEXT;
ALTER TABLE turn_type ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE turn_type ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE turn_type ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

UPDATE turn_type
SET slug = regexp_replace(lower(trim(name)), '[^a-z0-9]+', '_', 'g')
WHERE slug IS NULL
  AND name IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_turn_type_slug ON turn_type(slug);

DROP TRIGGER IF EXISTS trg_turn_type_set_updated_at ON turn_type;
CREATE TRIGGER trg_turn_type_set_updated_at
BEFORE UPDATE ON turn_type
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

