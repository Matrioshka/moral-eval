-- Add FK-based operational turn metadata. Keep existing text columns for now so
-- old views/imports continue to work during migration.
ALTER TABLE case_turn ADD COLUMN IF NOT EXISTS turn_type_id INTEGER;
ALTER TABLE case_turn ADD COLUMN IF NOT EXISTS pressure_type_id INTEGER;

UPDATE case_turn ct
SET turn_type_id = tt.turn_type_id
FROM turn_type tt
WHERE tt.slug = CASE
        WHEN regexp_replace(lower(trim(ct.turn_type::text)), '[^a-z0-9]+', '_', 'g') IN ('intervention', 'pressure', 'evidence_update') THEN 'followup'
        ELSE regexp_replace(lower(trim(ct.turn_type::text)), '[^a-z0-9]+', '_', 'g')
    END
  AND ct.turn_type_id IS DISTINCT FROM tt.turn_type_id;

UPDATE case_turn ct
SET pressure_type_id = pt.pressure_type_id
FROM pressure_type pt
WHERE pt.slug = CASE
        WHEN ct.pressure_type IS NULL OR length(trim(ct.pressure_type::text)) = 0 THEN 'none'
        ELSE regexp_replace(lower(trim(ct.pressure_type::text)), '[^a-z0-9]+', '_', 'g')
    END
  AND ct.pressure_type_id IS DISTINCT FROM pt.pressure_type_id;

CREATE INDEX IF NOT EXISTS idx_case_turn_turn_type_id ON case_turn(turn_type_id);
CREATE INDEX IF NOT EXISTS idx_case_turn_pressure_type_id ON case_turn(pressure_type_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_case_turn_turn_type') THEN
        ALTER TABLE case_turn
            ADD CONSTRAINT fk_case_turn_turn_type
            FOREIGN KEY (turn_type_id)
            REFERENCES turn_type(turn_type_id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_case_turn_pressure_type') THEN
        ALTER TABLE case_turn
            ADD CONSTRAINT fk_case_turn_pressure_type
            FOREIGN KEY (pressure_type_id)
            REFERENCES pressure_type(pressure_type_id);
    END IF;
END $$;

-- Operational scorer dimension.
CREATE TABLE IF NOT EXISTS scorer (
    scorer_id BIGSERIAL PRIMARY KEY,
    scorer_type TEXT NOT NULL,
    name TEXT NOT NULL,
    model_name TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT scorer_type_not_blank CHECK (length(trim(scorer_type)) > 0),
    CONSTRAINT scorer_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_scorer_type_name_model
    ON scorer (scorer_type, name, COALESCE(model_name, ''));

DROP TRIGGER IF EXISTS trg_scorer_set_updated_at ON scorer;
CREATE TRIGGER trg_scorer_set_updated_at
BEFORE UPDATE ON scorer
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

INSERT INTO scorer (scorer_type, name, model_name, description)
VALUES
    (
        'imported_manual_audit',
        'Imported manual audit',
        NULL,
        'Scores imported from project manual-audit CSV artefacts. The original audit file remains the source-of-truth artefact.'
    ),
    (
        'deterministic',
        'schema_v2_1_scorer',
        NULL,
        'Deterministic schema-v2.1 scorer/checker for structured tuple extraction, field validity, and bound/consistency checks.'
