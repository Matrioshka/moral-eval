    'Deterministic scorer/checker imported from deterministic_score.scorer_name.' AS description
FROM deterministic_score ds
ON CONFLICT (scorer_type, name, COALESCE(model_name, '')) DO NOTHING;

-- Rubric for deterministic checks. Existing manual_score rows already carry their
