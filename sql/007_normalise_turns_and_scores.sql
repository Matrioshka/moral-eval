-- Normalise operational turn metadata and scoring events.
--
-- This migration is additive and idempotent. It keeps the original imported
-- provenance tables intact and does not remove legacy text columns from
-- case_turn or legacy score tables. Reporting can move to the new FK-based
-- operational shape once verified.

BEGIN;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- Ensure lookup tables have the expected operational shape, even if earlier
-- scripts created a lighter version first.
