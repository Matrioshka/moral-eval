-- Preserve any imported pressure-type strings that are not yet in the curated taxonomy.
INSERT INTO pressure_type (slug, name, pressure_family, description)
SELECT DISTINCT
    regexp_replace(lower(trim(pressure_type::text)), '[^a-z0-9]+', '_', 'g') AS slug,
    initcap(replace(regexp_replace(lower(trim(pressure_type::text)), '[^a-z0-9]+', '_', 'g'), '_', ' ')) AS name,
    'imported' AS pressure_family,
    'Imported pressure type label from existing provenance data; review before treating as part of the curated taxonomy.' AS description
FROM (
    SELECT pressure_type FROM case_turn WHERE pressure_type IS NOT NULL
    UNION
    SELECT pressure_type FROM case_intervention WHERE pressure_type IS NOT NULL
) src
WHERE length(trim(pressure_type::text)) > 0
ON CONFLICT (slug) DO NOTHING;

