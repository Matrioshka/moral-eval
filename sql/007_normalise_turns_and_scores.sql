-- Unified operational score events. A score_event is one act of scoring one
-- response by one scorer under one rubric/source. It is intentionally response-
-- level only; case and turn are derived via response -> case_turn -> eval_case.
CREATE TABLE IF NOT EXISTS score_event (
    score_event_id BIGSERIAL PRIMARY KEY,
    response_id BIGINT NOT NULL REFERENCES response(response_id) ON DELETE CASCADE,
    scorer_id BIGINT NOT NULL REFERENCES scorer(scorer_id),
    rubric_id BIGINT REFERENCES rubric(rubric_id),
    failure_class_id BIGINT REFERENCES failure_class(failure_class_id),
    score NUMERIC,
    label TEXT,
    rationale TEXT,
    notes TEXT,
    confidence NUMERIC,
    confidence_label TEXT,
    source_file_id BIGINT REFERENCES source_file(source_file_id),
    source_row INTEGER,
    legacy_manual_score_id BIGINT REFERENCES manual_score(manual_score_id) ON DELETE SET NULL,
    legacy_deterministic_score_id BIGINT REFERENCES deterministic_score(deterministic_score_id) ON DELETE SET NULL,
    raw_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT score_event_confidence_range CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_score_event_legacy_manual
    ON score_event (legacy_manual_score_id)
    WHERE legacy_manual_score_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_score_event_legacy_deterministic
    ON score_event (legacy_deterministic_score_id)
    WHERE legacy_deterministic_score_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_score_event_response_id ON score_event(response_id);
CREATE INDEX IF NOT EXISTS idx_score_event_scorer_id ON score_event(scorer_id);
CREATE INDEX IF NOT EXISTS idx_score_event_rubric_id ON score_event(rubric_id);
CREATE INDEX IF NOT EXISTS idx_score_event_failure_class_id ON score_event(failure_class_id);

DROP TRIGGER IF EXISTS trg_score_event_set_updated_at ON score_event;
CREATE TRIGGER trg_score_event_set_updated_at
BEFORE UPDATE ON score_event
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- Manual/imported audit scores. manual_score.notes is treated as the audit
-- rationale because it usually contains the judgement explanation. Importer or
-- provenance comments belong in score_event.notes.
INSERT INTO score_event (
    response_id,
    scorer_id,
    rubric_id,
    failure_class_id,
    score,
    label,
    rationale,
    notes,
    confidence,
    confidence_label,
    source_file_id,
    source_row,
    legacy_manual_score_id,
    raw_metadata
)
SELECT
    r.response_id,
    sc.scorer_id,
    ms.rubric_id,
    ms.primary_failure_class_id,
    ms.score_0_to_3 AS score,
    NULLIF(trim(ms.action), '') AS label,
    NULLIF(trim(ms.notes), '') AS rationale,
    'Imported from manual_score; original row retained in raw_metadata and legacy_manual_score_id.' AS notes,
    CASE
        WHEN ms.confidence ~ '^[0-9]+(\.[0-9]+)?$' THEN ms.confidence::numeric
        ELSE NULL::numeric
    END AS confidence,
    CASE
        WHEN ms.confidence IS NOT NULL AND ms.confidence !~ '^[0-9]+(\.[0-9]+)?$' THEN ms.confidence
        ELSE NULL::text
    END AS confidence_label,
    ms.source_file_id,
    ms.source_row,
    ms.manual_score_id,
    jsonb_build_object(
        'legacy_table', 'manual_score',
        'action', ms.action,
        'confidence', ms.confidence,
        'raw_row', ms.raw_row
    ) AS raw_metadata
FROM manual_score ms
JOIN response r ON r.legacy_model_response_id = ms.response_id
JOIN scorer sc
  ON sc.scorer_type = 'imported_manual_audit'
 AND sc.name = 'Imported manual audit'
 AND sc.model_name IS NULL
ON CONFLICT (legacy_manual_score_id) DO UPDATE SET
    response_id = EXCLUDED.response_id,
    scorer_id = EXCLUDED.scorer_id,
    rubric_id = EXCLUDED.rubric_id,
    failure_class_id = EXCLUDED.failure_class_id,
    score = EXCLUDED.score,
    label = EXCLUDED.label,
    rationale = EXCLUDED.rationale,
    notes = EXCLUDED.notes,
    confidence = EXCLUDED.confidence,
    confidence_label = EXCLUDED.confidence_label,
    source_file_id = EXCLUDED.source_file_id,
    source_row = EXCLUDED.source_row,
    raw_metadata = EXCLUDED.raw_metadata,
    updated_at = now();

-- Deterministic checks. These are programmatic checks, not independent moral
-- judgements. Numeric score text is copied into score when possible; otherwise
-- the original answer/score_value is preserved in label/raw_metadata.
INSERT INTO score_event (
    response_id,
    scorer_id,
    rubric_id,
    failure_class_id,
    score,
    label,
    rationale,
    notes,
    confidence,
    confidence_label,
    source_file_id,
    source_row,
    legacy_deterministic_score_id,
    raw_metadata
)
SELECT
    r.response_id,
    sc.scorer_id,
    rb.rubric_id,
    NULL::bigint AS failure_class_id,
    CASE
        WHEN ds.score_value ~ '^[+-]?[0-9]+(\.[0-9]+)?$' THEN ds.score_value::numeric
        ELSE NULL::numeric
    END AS score,
    COALESCE(NULLIF(trim(ds.answer), ''), NULLIF(trim(ds.score_value), '')) AS label,
    NULLIF(trim(ds.explanation), '') AS rationale,
    'Imported from deterministic_score. Treat as a programmatic diagnostic/check rather than a human moral audit.' AS notes,
    NULL::numeric AS confidence,
    NULL::text AS confidence_label,
    ds.source_file_id,
    ds.source_row,
    ds.deterministic_score_id,
    jsonb_build_object(
        'legacy_table', 'deterministic_score',
        'scorer_name', ds.scorer_name,
        'score_value', ds.score_value,
        'answer', ds.answer,
        'metadata', ds.metadata,
        'raw_row', ds.raw_row
    ) AS raw_metadata
FROM deterministic_score ds
JOIN response r ON r.legacy_model_response_id = ds.response_id
JOIN scorer sc
  ON sc.scorer_type = 'deterministic'
 AND sc.name = COALESCE(NULLIF(trim(ds.scorer_name), ''), 'deterministic_scorer')
 AND sc.model_name IS NULL
JOIN rubric rb ON rb.rubric_name = 'deterministic_schema_check'
ON CONFLICT (legacy_deterministic_score_id) DO UPDATE SET
    response_id = EXCLUDED.response_id,
    scorer_id = EXCLUDED.scorer_id,
    rubric_id = EXCLUDED.rubric_id,
    failure_class_id = EXCLUDED.failure_class_id,
    score = EXCLUDED.score,
    label = EXCLUDED.label,
    rationale = EXCLUDED.rationale,
    notes = EXCLUDED.notes,
    source_file_id = EXCLUDED.source_file_id,
    source_row = EXCLUDED.source_row,
    raw_metadata = EXCLUDED.raw_metadata,
    updated_at = now();

-- Convenience summary for local execution.
SELECT 'case_turn_with_turn_type_id' AS metric, count(*) AS value
FROM case_turn
WHERE turn_type_id IS NOT NULL
UNION ALL
SELECT 'case_turn_with_pressure_type_id' AS metric, count(*) AS value
FROM case_turn
WHERE pressure_type_id IS NOT NULL
UNION ALL
SELECT 'scorers' AS metric, count(*) AS value
FROM scorer
UNION ALL
SELECT 'score_events' AS metric, count(*) AS value
FROM score_event
ORDER BY metric;

COMMIT;
