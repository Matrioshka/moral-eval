ON CONFLICT (scorer_type, name, COALESCE(model_name, '')) DO UPDATE SET
    description = EXCLUDED.description,
    updated_at = now();

-- Preserve any distinct deterministic scorer names found in imported rows.
INSERT INTO scorer (scorer_type, name, model_name, description)
SELECT DISTINCT
    'deterministic' AS scorer_type,
    COALESCE(NULLIF(trim(ds.scorer_name), ''), 'deterministic_scorer') AS name,
